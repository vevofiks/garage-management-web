/**
 * src/lib/db.ts
 *
 * Postgres (Neon) connection + schema bootstrap. This module is SERVER-ONLY —
 * import it only inside:
 *   - Next.js API Route Handlers (src/app/api/.../route.ts)
 *   - Next.js Server Components / Server Actions
 *
 * `db.prepare(sql).get/.all/.run(...)` keeps the call shape the rest of the
 * codebase already uses, converting `?` placeholders to `$1,$2,...` and
 * running them through `pg`. `db.transaction(fn)` runs `fn` on a single
 * dedicated client (BEGIN/COMMIT/ROLLBACK), and uses AsyncLocalStorage so
 * that nested `db.prepare(...)` calls made inside `fn` (via this same
 * exported `db`) transparently reuse that client instead of a fresh pool
 * connection.
 */

import { AsyncLocalStorage } from 'async_hooks';
import { Pool, PoolClient, types } from 'pg';
import { hashPassword } from './auth';

// `pg` returns BIGINT/NUMERIC as strings by default (they don't fit safely
// in a JS number in general) — but this app's ids and money amounts are well
// within safe-integer/float range, and the rest of the codebase (arithmetic,
// JSON responses, frontend formatting) assumes plain numbers throughout. This
// also matters for databases that predate this schema (created when ids were
// BIGINT), not just fresh installs.
types.setTypeParser(20 /* int8 */, (val) => parseInt(val, 10));
types.setTypeParser(1700 /* numeric */, (val) => parseFloat(val));

export type Row = Record<string, unknown>;

export interface Statement {
  all(...params: unknown[]): Promise<Row[]>;
  get(...params: unknown[]): Promise<Row | undefined>;
  run(...params: unknown[]): Promise<{ changes: number; lastInsertRowid: number | undefined }>;
}

// eslint-disable-next-line @typescript-eslint/no-explicit-any
type AnyFn = (...args: any[]) => any;

export interface Db {
  prepare(sql: string): Statement;
  transaction<T extends AnyFn>(fn: T): (...args: Parameters<T>) => Promise<Awaited<ReturnType<T>>>;
}

let pool: Pool | null = null;
const txContext = new AsyncLocalStorage<PoolClient>();

function getPool(): Pool {
  if (!pool) {
    const connectionString = process.env.DATABASE_URL;
    if (!connectionString) {
      throw new Error('DATABASE_URL environment variable is not set');
    }
    pool = new Pool({
      connectionString,
      ssl: { rejectUnauthorized: false },
      max: 10,
      idleTimeoutMillis: 30000,
      connectionTimeoutMillis: 8000,
    });
  }
  return pool;
}

function getExecutor(): Pool | PoolClient {
  return txContext.getStore() ?? getPool();
}

/** `?` -> `$1, $2, ...`, positional and order-preserving. */
function toPgSql(sql: string): string {
  let i = 0;
  return sql.replace(/\?/g, () => `$${++i}`);
}

/** Allows both `.all(...paramsArray)` (common) and `.all(paramsArray)` (single-array-arg) call styles. */
function flattenArgs(args: unknown[]): unknown[] {
  if (args.length === 1 && Array.isArray(args[0])) return args[0];
  return args;
}

let bootstrapPromise: Promise<void> | null = null;

function ensureBootstrapped(): Promise<void> {
  if (!bootstrapPromise) bootstrapPromise = bootstrapDatabase();
  return bootstrapPromise;
}

function prepare(sql: string): Statement {
  const pgSql = toPgSql(sql);
  return {
    async all(...args: unknown[]) {
      await ensureBootstrapped();
      const res = await getExecutor().query(pgSql, flattenArgs(args));
      return res.rows;
    },
    async get(...args: unknown[]) {
      await ensureBootstrapped();
      const res = await getExecutor().query(pgSql, flattenArgs(args));
      return res.rows[0];
    },
    async run(...args: unknown[]) {
      await ensureBootstrapped();
      const res = await getExecutor().query(pgSql, flattenArgs(args));
      return { changes: res.rowCount ?? 0, lastInsertRowid: res.rows[0]?.id };
    },
  };
}

function transaction<T extends AnyFn>(
  fn: T
): (...args: Parameters<T>) => Promise<Awaited<ReturnType<T>>> {
  return async (...args: Parameters<T>) => {
    await ensureBootstrapped();
    const client = await getPool().connect();
    try {
      await client.query('BEGIN');
      const result = await txContext.run(client, () => fn(...args));
      await client.query('COMMIT');
      return result;
    } catch (err) {
      try {
        await client.query('ROLLBACK');
      } catch {
        // ignore rollback failure, original error is what matters
      }
      throw err;
    } finally {
      client.release();
    }
  };
}

const db: Db = { prepare, transaction };

async function bootstrapDatabase(): Promise<void> {
  const p = getPool();

  await p.query(`
    -- Users & roles
    CREATE TABLE IF NOT EXISTS users (
      id          INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
      username    TEXT NOT NULL UNIQUE,
      password    TEXT NOT NULL,
      role        TEXT NOT NULL CHECK(role IN ('admin', 'staff')),
      created_at  TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
      updated_at  TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS sessions (
      token       TEXT PRIMARY KEY,
      user_id     INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      expires_at  TEXT NOT NULL,
      created_at  TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
    );

    -- Customers
    CREATE TABLE IF NOT EXISTS customers (
      id              INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
      name            TEXT NOT NULL,
      phone           TEXT,
      address         TEXT,
      vehicle_number  TEXT,
      vehicle_model   TEXT,
      created_at      TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
      updated_at      TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
    );

    -- Vehicles
    CREATE TABLE IF NOT EXISTS vehicles (
      id              INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
      customer_id     INTEGER NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
      vehicle_number  TEXT,
      vehicle_model   TEXT,
      created_at      TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
      updated_at      TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
    );

    -- Invoices
    CREATE TABLE IF NOT EXISTS invoices (
      id                  INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
      customer_id         INTEGER NOT NULL REFERENCES customers(id),
      vehicle_id          INTEGER REFERENCES vehicles(id),
      notes               TEXT,
      total_amount        DOUBLE PRECISION NOT NULL DEFAULT 0,
      paid_amount         DOUBLE PRECISION NOT NULL DEFAULT 0,
      payment_status      TEXT NOT NULL DEFAULT 'unpaid' CHECK(payment_status IN ('unpaid', 'partial', 'paid')),
      payment_method      TEXT NOT NULL DEFAULT 'cash' CHECK(payment_method IN ('cash', 'card', 'both', 'other')),
      payment_method_note TEXT,
      created_at          TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
      updated_at          TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
    );

    -- Invoice line items
    CREATE TABLE IF NOT EXISTS invoice_items (
      id          INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
      invoice_id  INTEGER NOT NULL REFERENCES invoices(id),
      description TEXT NOT NULL,
      type        TEXT NOT NULL CHECK(type IN ('part', 'labor', 'discount')),
      amount      DOUBLE PRECISION NOT NULL DEFAULT 0
    );

    CREATE TABLE IF NOT EXISTS predefined_services (
      id          INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
      name        TEXT NOT NULL UNIQUE,
      created_at  TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS expense_categories (
      id          INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
      name        TEXT NOT NULL UNIQUE,
      created_at  TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS expenses (
      id           INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
      category_id  INTEGER NOT NULL REFERENCES expense_categories(id),
      amount       DOUBLE PRECISION NOT NULL,
      notes        TEXT,
      date         TEXT NOT NULL,
      created_at   TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS audit_logs (
      id          INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
      user_id     INTEGER,
      username    TEXT NOT NULL,
      action      TEXT NOT NULL,
      description TEXT NOT NULL,
      created_at  TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS settings (
      key         TEXT PRIMARY KEY,
      value       TEXT NOT NULL,
      updated_at  TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
    );

    CREATE INDEX IF NOT EXISTS idx_customers_name ON customers(name);
    CREATE INDEX IF NOT EXISTS idx_customers_phone ON customers(phone);
    CREATE INDEX IF NOT EXISTS idx_customers_vehicle_number ON customers(vehicle_number);
    CREATE INDEX IF NOT EXISTS idx_vehicles_customer_id ON vehicles(customer_id);
    CREATE INDEX IF NOT EXISTS idx_vehicles_vehicle_number ON vehicles(vehicle_number);
    CREATE INDEX IF NOT EXISTS idx_invoices_customer_id ON invoices(customer_id);
    CREATE INDEX IF NOT EXISTS idx_invoices_vehicle_id ON invoices(vehicle_id);
    CREATE INDEX IF NOT EXISTS idx_invoice_items_invoice_id ON invoice_items(invoice_id);
    CREATE INDEX IF NOT EXISTS idx_invoices_created_at ON invoices(created_at);
    CREATE INDEX IF NOT EXISTS idx_sessions_user_id ON sessions(user_id);
    CREATE INDEX IF NOT EXISTS idx_expenses_category_id ON expenses(category_id);
    CREATE INDEX IF NOT EXISTS idx_expenses_date ON expenses(date);
    CREATE INDEX IF NOT EXISTS idx_audit_logs_created_at ON audit_logs(created_at);
  `);

  const EXPENSE_CATEGORIES = ['Parts Purchase', 'Rent', 'Utilities', 'Salaries'];
  for (const name of EXPENSE_CATEGORIES) {
    await p.query('INSERT INTO expense_categories (name) VALUES ($1) ON CONFLICT (name) DO NOTHING', [name]);
  }

  const PREDEFINED_SERVICES = [
    'Engine oil & Oil filter change',
    'Air filter change',
    'AC cabin filter change',
    'Front brake pad change',
    'Rear brake shoe change',
    'Gear oil change',
    'Differential oil change',
    'Wiper blade change',
    'Radiator removing and fitting',
    'AC hose removing and fitting',
    'AC hose crimping',
    'AC compressor change',
    'Condenser change',
    'Expansion valve change',
  ];
  for (const name of PREDEFINED_SERVICES) {
    await p.query('INSERT INTO predefined_services (name) VALUES ($1) ON CONFLICT (name) DO NOTHING', [name]);
  }

  const { rows } = await p.query('SELECT COUNT(*)::int AS count FROM users');
  if (rows[0].count === 0) {
    const defaultPasswordHash = hashPassword('admin123');
    await p.query(
      'INSERT INTO users (username, password, role) VALUES ($1, $2, $3) ON CONFLICT (username) DO NOTHING',
      ['admin', defaultPasswordHash, 'admin']
    );
  }
}

export async function getSetting(key: string, defaultValue: string = ''): Promise<string> {
  const row = await db.prepare('SELECT value FROM settings WHERE key = ?').get(key);
  return row ? (row.value as string) : defaultValue;
}

export async function setSetting(key: string, value: string): Promise<void> {
  await db
    .prepare('INSERT INTO settings (key, value) VALUES (?, ?) ON CONFLICT(key) DO UPDATE SET value = excluded.value')
    .run(key, value);
}

export default db;
